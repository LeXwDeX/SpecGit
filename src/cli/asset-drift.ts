/**
 * Generated-asset drift report (#308): the read-side upgrade check behind
 * `specgit status`. This module owns NO filesystem rules of its own — it
 * reuses the exact desired-state builders the writers converge
 * (`buildHarnessDesiredState` + the `.gitignore` transform for init,
 * `buildAgentSurfaceDesiredState` for setup) and reads them through the
 * reconciler's `inspectManagedAssets`, so the checklist can never drift
 * from the writer. It never writes, deletes, chmods, prompts, calls
 * gh/glab, or edits provider declarations; the one mutating seam the init
 * writer has (the policy `portWrite`) is simply not built here — policy is
 * authoritative content, not generated bytes.
 *
 * Report contract (stable, machine-facing; names and codes never localize):
 *
 * - per asset: `current` | `stale` | `missing` | `conflict` with codes
 *   `asset_stale` / `asset_missing` / `asset_conflict`;
 * - per surface: `init` → `specgit init --force` (or `specgit init` when
 *   no policy exists yet), `opencode` → `specgit setup --tool opencode`,
 *   `generic` → `specgit setup --tool generic`; an optional setup surface
 *   with nothing on disk is `absent` — clean, no fix, no missing-file
 *   list;
 * - `complete` is the fail-closed completeness claim: true only when
 *   every part of the desired state got a claim (or a proven opt-out in
 *   `skipped`) — "no detected drift" is never "proven clean";
 * - `clean` requires `complete` AND no inspected surface stale/missing/
 *   conflict;
 * - `uninspected` names every desired part NO claim was made about
 *   (undecided platform — including an invalid providers declaration —
 *   unresolved default branch, unmergeable hooks.json, failed probes,
 *   unreadable evidence) — each an unknown that makes the report
 *   incomplete; `skipped` names intentional, proven non-applicability
 *   (the committed-authoritative `.gitignore` opt-out) — proof, not an
 *   unknown, so it never makes a report incomplete. Status never guesses
 *   where the writer itself would guess.
 */

